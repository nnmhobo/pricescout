"""
Спільна логіка визначення категорії за кодом ресурсу (ДБН/АВК-5).

Обидва парсери кошторисів — kostoris_parser.py (КД_ПВР) та rlmt_parser.py
(КД_РЛМТ) — читають один і той самий каталог кодів ресурсів (С111, С130-62,
діапазони обладнання 1100-1999, під-коди С100-xxxx тощо). Цей модуль —
єдине джерело істини для цієї логіки, щоб два парсери не розійшлись.

Витягнуто дослівно з kostoris_parser.py (2026-08) — без зміни поведінки.
"""

import re


def derive_category(code: str) -> str:
    """Мапить код ресурсу (напр. 'С111-91', '&К100-42', 'С1630-2028') на
    категорію для відображення. `code` може ще містити провідний маркер
    &/+ та пробіли навколо — функція сама їх прибирає."""
    code_clean = (code or '').lstrip('&+').strip()
    num_match = re.match(r'^[СCКк]?(\d+)', code_clean)
    num = int(num_match.group(1)) if num_match else 0

    if re.match(r'^[КкKk]', code_clean):
        return 'Конструкції збірні'

    # ── С-resource catalog codes (verified from DB analysis) ──
    # С111 = загальнобудівельні матеріали (металовироби, кріплення, цемент, фарби...)
    if num == 111 or (num == 11 and num_match and len(num_match.group(1)) == 2):
        return 'Підлоги, покрівлі, покриття'
    # С112 = пиломатеріали (дошки, бруски, бруси)
    if num == 112:
        return 'Пиломатеріали'
    # С113 = трубопроводи, фітинги, профільний метал
    if num == 113:
        return 'Трубопроводи та фітинги'
    # С114 = теплоізоляція (мінвата, пінопластирол)
    if num == 114:
        return 'Теплоізоляція'
    # С121 = металоконструкції
    if num == 121:
        return 'Металоконструкції'
    # С123 = вікна та двері (металопластикові, алюмінієві)
    if num == 123:
        return 'Вікна та двері'
    # С124 = арматура сталева
    if num == 124:
        return 'Арматура та металоконструкції'
    # С130 = heating/ventilation mixed zbіrnyk
    # sub-code 62 = ventilation equipment (recuperators, exhaust units)
    if num == 130:
        sub_match = re.search(r'С130-(\d+)', code_clean)
        sub = int(sub_match.group(1)) if sub_match else 0
        if sub == 62:
            return 'Вентиляція та кондиціонування'
        return 'Теплопостачання та опалення'
    # С142/С147 = спецматеріали (вода, дріт)
    if num in (142, 147):
        return 'Спеціальні роботи'
    # С151/С152 = кабелі (силові, сигналізації)
    if 151 <= num <= 152:
        return 'Кабельні системи'
    # Other С1xx codes
    if 101 <= num <= 110:
        return 'Конструктивні роботи'
    if 115 <= num <= 120:
        return 'Захист конструкцій'
    if 125 <= num <= 129:
        return 'Мережі (водопостачання, газ)'
    if 131 <= num <= 149:
        return 'Спеціальні роботи'

    # ── Equipment montage codes (verified from DB) ────────────
    if 1100 <= num <= 1119:
        return 'Теплотехнічне устаткування'
    if 1300 <= num <= 1399:
        return 'Вентиляція та кондиціонування'
    if 1400 <= num <= 1419:
        return 'Санітарно-технічне устаткування'
    if 1421 <= num <= 1429:
        return 'Будівельні матеріали'
    if 1500 <= num <= 1529:
        return 'Електрообладнання'
    if 1530 <= num <= 1560:
        return 'Кабельні системи'
    if 1600 <= num <= 1629:
        return 'Охорона та сигналізація'
    if 1630 <= num <= 1699:
        return 'Теплопостачання та опалення'
    if 1700 <= num <= 1799:
        return 'Автоматизація (КВП)'
    if 1800 <= num <= 1899:
        return 'Вантажопідйомне устаткування'
    if num == 1999:
        return 'Енергоносії'
    if num >= 1000:
        return 'Інше устаткування'

    # ── С100-xxxx: sub-code determines category ───────────────
    if num == 100:
        sub_match = re.search(r'\d{3,4}[-\s]*(\d{4,6})', code_clean)
        sub = int(sub_match.group(1)) if sub_match else 0
        if 1500 <= sub <= 1529:
            return 'Електрообладнання'
        if 1530 <= sub <= 1560:
            return 'Кабельні системи'
        if 1600 <= sub <= 1629:
            return 'Охорона та сигналізація'
        if 1630 <= sub <= 1699:
            return 'Теплопостачання та опалення'
        if 1700 <= sub <= 1799:
            return 'Автоматизація (КВП)'
        if 1900 <= sub <= 1999:
            return 'Теплотехнічне устаткування'
        return 'Електрообладнання'

    return 'Матеріали будівельні'
